// Build-time geography: real Natural Earth coastlines + a 650-seat UK cartogram.
const https=require("https"),fs=require("fs");
const topo=require("topojson-client");
function get(url){return new Promise((res,rej)=>{https.get(url,r=>{
  if(r.statusCode>=300&&r.headers.location)return get(r.headers.location).then(res,rej);
  let d="";r.on("data",c=>d+=c);r.on("end",()=>res(d));}).on("error",rej)})}
const PX=(lon,lat)=>[(lon+180)/360*1000,(90-lat)/180*500];
(async()=>{
  const land=JSON.parse(await get("https://unpkg.com/world-atlas@2.0.2/land-110m.json"));
  const countries=JSON.parse(await get("https://unpkg.com/world-atlas@2.0.2/countries-110m.json"));
  const landGeo=topo.feature(land,land.objects.land);
  const paths=[];
  for(const poly of landGeo.features[0].geometry.coordinates){
    for(const ring of poly){
      const pts=ring.map(([lo,la])=>PX(lo,la).map(v=>Math.round(v*10)/10));
      paths.push("M"+pts.map(p=>p[0]+","+p[1]).join("L")+"Z");
    }
  }
  // ---- UK: outline + 650 seat cells ----
  const cgeo=topo.feature(countries,countries.objects.countries);
  const uk=cgeo.features.find(f=>f.id==="826"||/United Kingdom/i.test(f.properties&&f.properties.name||""));
  if(!uk)throw new Error("UK not found");
  const rings=uk.geometry.type==="Polygon"?[uk.geometry.coordinates]:uk.geometry.coordinates;
  // local projection for UK box
  const LON0=-8.7,LON1=2.0,LAT0=49.8,LAT1=61.0,W=340,H=560,PAD=8;
  const ux=lo=>PAD+(lo-LON0)/(LON1-LON0)*(W-2*PAD);
  const uy=la=>PAD+(LAT1-la)/(LAT1-LAT0)*(H-2*PAD);
  const ukPaths=[],allRings=[];
  for(const poly of rings){for(const ring of poly){
    allRings.push(ring);
    ukPaths.push("M"+ring.map(([lo,la])=>Math.round(ux(lo)*10)/10+","+Math.round(uy(la)*10)/10).join("L")+"Z");}}
  function inside(lo,la){let inAny=false;
    for(const ring of allRings){let c=false;
      for(let i=0,j=ring.length-1;i<ring.length;j=i++){
        const[xi,yi]=ring[i],[xj,yj]=ring[j];
        if(((yi>la)!=(yj>la))&&(lo<(xj-xi)*(la-yi)/(yj-yi)+xi))c=!c;}
      if(c)inAny=true;}
    return inAny;}
  function regionOf(lo,la){
    if(lo<-5.15&&la>53.9&&la<55.4)return"ni";
    if(la>54.95)return"scot";
    const dLon=lo+0.12,dLat=la-51.5;
    if(Math.sqrt(dLon*dLon*0.62+dLat*dLat)<0.42)return"lon";
    if(lo<=-2.68&&la>=51.33&&la<=53.45)return"wales";
    if(la>53.05)return"north";
    if(la>52.0)return"mid";
    return"south";}
  const buckets={scot:[],ni:[],wales:[],lon:[],north:[],mid:[],south:[]};
  for(let la=LAT0;la<=LAT1;la+=0.062){for(let lo=LON0;lo<=LON1;lo+=0.105){
    if(!inside(lo,la))continue;
    buckets[regionOf(lo,la)].push([Math.round(ux(lo)*10)/10,Math.round(uy(la)*10)/10]);}}
  const TARGET={scot:57,ni:18,wales:32,north:124,mid:100,south:244,lon:75};
  const seats=[];
  for(const[reg,want]of Object.entries(TARGET)){
    if(reg==="lon")continue;
    let cells=buckets[reg].sort((a,b)=>a[1]-b[1]||a[0]-b[0]);
    if(cells.length>=want){const out=[];for(let i=0;i<want;i++)out.push(cells[Math.floor(i*cells.length/want)]);cells=out;}
    else{const base=cells.slice();let i=0;
      while(cells.length<want){const c=base[i%base.length];cells.push([c[0]+((i*7)%13-6)*0.9,c[1]+((i*5)%11-5)*0.9]);i++;}}
    cells.forEach(c=>seats.push([c[0],c[1],reg]));
  }
  // London inset: 75 cells in a neat grid, bottom-right
  const IN={x:236,y:430,cols:9,cell:10.6};
  for(let i=0;i<75;i++){const r=Math.floor(i/IN.cols),c2=i%IN.cols;
    seats.push([Math.round((IN.x+c2*IN.cell)*10)/10,Math.round((IN.y+r*IN.cell)*10)/10,"lon"]);}
  const counts={};seats.forEach(s=>counts[s[2]]=(counts[s[2]]||0)+1);
  console.log("region cells:",counts,"total:",seats.length);
  if(seats.length!==650)throw new Error("seat count "+seats.length);
  const out="/* generated by tools-build-geo.js — Natural Earth 110m via world-atlas */\n"
    +"const WORLD_GEO="+JSON.stringify(paths)+";\n"
    +"const UK_MAP={W:"+W+",H:"+H+",outline:"+JSON.stringify(ukPaths)
    +",inset:{x:"+(IN.x-6)+",y:"+(IN.y-16)+",w:"+(IN.cols*IN.cell+10)+",h:"+(Math.ceil(75/IN.cols)*IN.cell+22)+"}"
    +",seats:"+JSON.stringify(seats)+"};\n";
  fs.writeFileSync("geo.js",out);
  console.log("geo.js:",(out.length/1024).toFixed(1)+"KB · world paths:",paths.length,"· uk outline rings:",ukPaths.length);
})().catch(e=>{console.error("GEO BUILD FAIL:",e.message);process.exit(1)});
